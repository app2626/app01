// 2. Extract CSS and JS from src/*.html into versioned static assets for Edge Caching
function extractTagBodies(html, tagName) {
  const re = new RegExp(`<${tagName}[^>]*>([\\s\\S]*?)<\\/${tagName}>`, 'gi');
  const parts = [];
  let m;
  while ((m = re.exec(html)) !== null) parts.push(m[1]);
  return parts.length ? parts.join('\n') : html;
}

const CLIENT_BRIDGE_JS = `(function() {
  function makeRunner(onOk, onErr) {
    function call(endpoint, body) {
      fetch(endpoint, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(body)
      }).then(function(r) {
        return r.json().then(function(data) {
          if (!r.ok && (!data || data.status !== 'error')) {
            throw new Error((data && data.message) || ('HTTP ' + r.status));
          }
          return data;
        });
      }).then(function(res) {
        if (onOk) onOk(res);
      }).catch(function(err) {
        if (onErr) onErr(err);
      });
    }
    return {
      withSuccessHandler: function(fn) { return makeRunner(fn, onErr); },
      withFailureHandler: function(fn) { return makeRunner(onOk, fn); },
      apiHandler: function(action, payload, userToken) {
        call('/api', { action: action, payload: payload || {}, userToken: userToken || null });
      },
      setupDatabase: function(userToken) {
        call('/api/setup', { userToken: userToken || null });
      },
      getPublicConfig: function() {
        fetch('/api/public-config').then(function(r) { return r.json(); })
          .then(function(res) { if (onOk) onOk(res); })
          .catch(function(err) { if (onErr) onErr(err); });
      }
    };
  }
  window.google = window.google || {};
  window.google.script = {
    run: makeRunner(null, null),
    url: {
      getLocation: function(cb) {
        var sp = new URLSearchParams(window.location.search);
        var params = {};
        sp.forEach(function(v, k) {
          if (!params[k]) params[k] = [];
          params[k].push(v);
        });
        cb({ parameters: params, hash: (window.location.hash || '').replace(/^#/, '') });
      }
    },
    history: {
      push: function(_state, params, hash) {
        try {
          var sp = new URLSearchParams();
          if (params) {
            Object.keys(params).forEach(function(k) {
              var val = params[k];
              if (Array.isArray(val)) val.forEach(function(v) { sp.append(k, v); });
              else if (val !== undefined && val !== null && val !== '') sp.set(k, String(val));
            });
          }
          var qs = sp.toString();
          var url = window.location.pathname + (qs ? '?' + qs : '') + (hash ? '#' + hash : window.location.hash);
          window.history.replaceState(null, '', url);
        } catch (e) {}
      },
      setChangeHandler: function(fn) {
        window.addEventListener('popstate', function() {
          var sp = new URLSearchParams(window.location.search);
          var params = {};
          sp.forEach(function(v, k) {
            if (!params[k]) params[k] = [];
            params[k].push(v);
          });
          fn({ location: { parameters: params, hash: (window.location.hash || '').replace(/^#/, '') } });
        });
      }
    }
  };
})();`;

const indexHtmlRaw = fs.readFileSync(path.join(SRC, 'Index.html'), 'utf8');
const includeMatches = [...indexHtmlRaw.matchAll(/<\?!=\s*include\(['"]([^'"]+)['"]\);?\s*\?>/g)];

const cssChunks = [];
const jsChunks = [CLIENT_BRIDGE_JS];
for (const m of includeMatches) {
  const name = m[1];
  const content = fs.readFileSync(path.join(SRC, name + '.html'), 'utf8');
  if (name === 'CSS' || name === 'TailwindCSS') {
    cssChunks.push(extractTagBodies(content, 'style'));
  } else if (name === 'JS' || name.startsWith('JS_')) {
    jsChunks.push(extractTagBodies(content, 'script'));
  }
}

const cssBundle = cssChunks.join('\n');
const jsBundle = jsChunks.join(';\n')
  .replace(/จะอัปโหลดขึ้น Drive ตอนกดบันทึก/g, 'จะอัปโหลดขึ้น Cloud ตอนกดบันทึก')
  .replace(/อัปโหลดขึ้น Drive/g, 'อัปโหลดขึ้น Cloud')
  .replace(/ตั้งค่าแผ่นงานและข้อมูลทดสอบ/g, 'ตั้งค่าฐานข้อมูล Cloud และข้อมูลทดสอบ');

// Syntax-check combined JS bundle at build time
new vm.Script(jsBundle, { filename: 'app.bundle.js' });

const cssHash = crypto.createHash('sha256').update(cssBundle).digest('hex').slice(0, 10);
const jsHash = crypto.createHash('sha256').update(jsBundle).digest('hex').slice(0, 10);

const cssFileName = `styles.${cssHash}.css`;
const jsFileName = `app.${jsHash}.js`;

fs.writeFileSync(path.join(ASSETS_DIR, cssFileName), cssBundle, 'utf8');
fs.writeFileSync(path.join(ASSETS_DIR, jsFileName), jsBundle, 'utf8');

// Replace inline CSS/JS includes in Index.html with static <link> and <script> tags
let cssInjected = false;
let jsInjected = false;
const indexTemplate = indexHtmlRaw.replace(/<\?!=\s*include\(['"]([^'"]+)['"]\);?\s*\?>/g, (_m, name) => {
  if (name === 'CSS' || name === 'TailwindCSS') {
    if (cssInjected) return '';
    cssInjected = true;
    return `<link rel="stylesheet" href="/assets/${cssFileName}">`;
  }
  if (name === 'JS' || name.startsWith('JS_')) {
    if (jsInjected) return '';
    jsInjected = true;
    return `<script src="/assets/${jsFileName}"></script>`;
  }
  return '';
});

const assetsModule = `// Auto-generated by cloudflare/build.js — do not edit directly
export const INDEX_TEMPLATE = ${JSON.stringify(indexTemplate)};
export const CSS_ASSET = ${JSON.stringify('/assets/' + cssFileName)};
export const JS_ASSET = ${JSON.stringify('/assets/' + jsFileName)};
`;

fs.writeFileSync(path.join(DIST, 'assets.js'), assetsModule, 'utf8');

